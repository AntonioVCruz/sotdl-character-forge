import {test,expect} from '@playwright/test';
import {existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {buildOfficialLocalContext} from '../../tools/curation/official-local-context';
import {completeCore} from '../helpers/finalization-paths';
import {finalizeOfficialCore} from '../../packages/character-generator/official-core';
import {confirmPreview,savedCharacter} from '../helpers/library-browser';
const root=process.env.SOTDL_LOCAL_SOURCE_ROOT??process.cwd();
test.skip(!existsSync(resolve(root,'curation/pilot/table-closure.json')),'Requires verified local sources.');
test.setTimeout(120000);
test('previews, discards, revalidates sources and keeps a new character separate',async({page,context})=>{
  const c=await buildOfficialLocalContext(root,process.cwd()),d=await finalizeOfficialCore(await completeCore(c),c);
  await context.route('**/api/official/core',route=>route.fulfill({json:c}));
  await page.addInitScript(d=>localStorage.setItem('sotdl-official-core-draft@1',JSON.stringify(d)),d);
  await page.goto('/');await expect(page.getByRole('heading',{name:'Personagem finalizado',exact:true})).toBeVisible();
  const original=await savedCharacter(page,'core'),row=c.backgroundPlans.find(p=>p.state?.amount===1)!.rowId;
  await page.getByRole('combobox',{name:'Escolher Background',exact:true}).focus();
  await page.getByRole('combobox',{name:'Escolher Background',exact:true}).selectOption(row);
  await expect(page.getByRole('heading',{name:'Prévia de alterações não salvas'})).toBeFocused();
  expect(await savedCharacter(page,'core')).toBe(original);
  await expect(page.getByRole('button',{name:'Procedimentos Core / Only Human',exact:true})).toBeDisabled();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button',{name:'Confirmar e salvar alterações',exact:true})).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button',{name:'Descartar alterações',exact:true})).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('combobox',{name:'Escolher Background',exact:true})).toBeFocused();
  await expect(page.getByRole('heading',{name:'Personagem finalizado',exact:true})).toBeVisible();
  expect(await savedCharacter(page,'core')).toBe(original);
  await page.getByRole('combobox',{name:'Escolher Background',exact:true}).selectOption(row);
  await context.unroute('**/api/official/core');await context.route('**/api/official/core',route=>route.fulfill({json:{...c,implementationSha256:'f'.repeat(64)}}));
  await page.getByRole('button',{name:'Confirmar e salvar alterações',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'source-context-changed'})).toBeVisible();expect(await savedCharacter(page,'core')).toBe(original);
  await context.unroute('**/api/official/core');await context.route('**/api/official/core',route=>route.fulfill({json:c}));await confirmPreview(page);
  await page.getByLabel('Nome',{exact:true}).fill('Segundo personagem');await page.getByLabel('Seed',{exact:true}).fill('workspace-new');
  await page.getByRole('button',{name:'Gerar novo rascunho com estas escolhas',exact:true}).click();await confirmPreview(page);
  await expect(page.getByRole('combobox',{name:'Personagem salvo',exact:true}).locator('option')).toHaveCount(3);
  expect(JSON.parse((await savedCharacter(page,'core'))!).config.name).toBe('Segundo personagem');
  expect(await page.evaluate(()=>localStorage.getItem('sotdl-official-core-draft@1'))).toBe(JSON.stringify(d));
  await page.getByRole('combobox',{name:'Personagem salvo',exact:true}).selectOption('legacy:core');
  await expect(page.getByRole('heading',{name:d.config.name,exact:true})).toBeVisible();
  await page.reload();await expect(page.getByRole('combobox',{name:'Personagem salvo',exact:true})).toHaveValue('legacy:core');
  await expect(page.getByRole('heading',{name:d.config.name,exact:true})).toBeVisible();
});
test('detects an actual second-tab revision without overwriting it',async({page,context})=>{
  const c=await buildOfficialLocalContext(root,process.cwd()),d=await finalizeOfficialCore(await completeCore(c),c);
  await context.route('**/api/official/core',route=>route.fulfill({json:c}));
  await page.addInitScript(d=>localStorage.setItem('sotdl-official-core-draft@1',JSON.stringify(d)),d);
  await page.goto('/');await expect(page.getByRole('combobox',{name:'Personagem salvo',exact:true})).toContainText('revisão 1');
  const other=await context.newPage();await other.goto('/');await expect(other.getByRole('combobox',{name:'Personagem salvo',exact:true})).toContainText('revisão 1');
  const row=c.backgroundPlans.find(p=>p.state?.amount===1)!.rowId;
  await expect(other.getByRole('button',{name:'Baixar backup JSON privado',exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'Escolher Background',exact:true}).selectOption(row);
  await confirmPreview(page);const winner=await savedCharacter(page,'core');
  await expect(other.getByRole('alert')).toContainText('Outra aba alterou');
  await expect(other.getByRole('button',{name:'Baixar backup JSON privado',exact:true})).toHaveCount(0);
  await other.getByRole('combobox',{name:'Escolher Background',exact:true}).selectOption(row);
  await expect(other.getByRole('button',{name:'Confirmar e salvar alterações'})).toBeDisabled();
  expect(await savedCharacter(other,'core')).toBe(winner);
  await other.getByRole('button',{name:'Descartar prévia e recarregar versão salva'}).click();
  await expect(other.getByRole('heading',{name:'Prévia de alterações não salvas'})).toHaveCount(0);
  expect(await savedCharacter(other,'core')).toBe(winner);await other.close();
});
